// Helper function to check user's quota and verify they can access a new video
async function checkAndIncrementQuota(userId: string, videoId: string, userPlan: string): Promise<{ allowed: boolean; message?: string; quotaInfo?: any }> {
  try {
    // Check if this is a repeat video (should not count toward quota)
    const shouldCount = await shouldCountTowardQuota(userId, videoId);

    if (!shouldCount) {
      // Repeat video - unlimited practice, skip quota check
      console.log(`[Quota] Repeat video - allowing unlimited practice`);
      return { allowed: true };
    }

    // New video - count how many videos user has accessed today
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const todayTimestamp = Timestamp.fromDate(today);

    // Query userPracticeHistory for videos accessed today
    const practiceSnapshot = await db
      .collection('userPracticeHistory')
      .where('userId', '==', userId)
      .get();

    // Count docs with firstAccessed >= today (filtering in memory)
    const todayCount = practiceSnapshot.docs.filter(doc => {
      const data = doc.data();
      return data.contentType === 'youtube' &&
             data.firstAccessed &&
             data.firstAccessed.seconds >= todayTimestamp.seconds;
    }).length;

    // Get quota limit for user's plan
    const limits: Record<string, number> = {
      'guest': 0,
      'free': 3,
      'premium_monthly': 20,
      'premium_yearly': 20
    };

    const limit = limits[userPlan] || 0;

    console.log(`[Quota] Current usage: ${todayCount}/${limit} for plan ${userPlan}`);

    if (todayCount >= limit) {
      // Quota exhausted
      console.log(`[Quota] ❌ Quota exhausted for user ${userId}`);
      return {
        allowed: false,
        message: 'Daily video limit reached',
        quotaInfo: {
          used: todayCount,
          limit,
          remaining: 0,
          resetAt: new Date(today.getTime() + 24 * 60 * 60 * 1000).toISOString()
        }
      };
    }

    // Quota available - create practice history to increment quota
    console.log(`[Quota] ✅ Quota available, creating userPracticeHistory`);
    await createPracticeHistoryOnFirstAccess(userId, videoId);

    return { allowed: true };
  } catch (error) {
    console.error('❌ Error checking and incrementing quota:', error);
    // Allow access on error (fail open for better UX)
    return { allowed: true };
  }
}

// Helper function to format transcript with AI
async function formatTranscriptWithAI(
  transcript: any[],
  videoTitle?: string,
  contentId?: string
): Promise<any[] | null> {
  try {
    // Skip if transcript too short
    if (transcript.length < 3) {
      console.log('🤖 [AI] Skipping formatting - transcript too short');
      return null;
    }

    console.log('🤖 [AI] Starting AI formatting for', transcript.length, 'segments');

    // Use the improved processTranscript method directly
    const response = await aiService.processTranscript({
      content: {
        transcript: transcript.map(seg => ({
          text: seg.text || '',
          startTime: seg.startTime || 0,
          endTime: seg.endTime || 0
        })),
        videoTitle,
        language: 'ja'
      },
      splitForShadowing: true,
      maxSegmentLength: 20,
      addFurigana: false,
      includeTranslations: true
    }, {
      jlptLevel: 'N4',
      includeTranslations: true
    });

    if (!response.success || !response.data) {
      console.error('❌ [AI] Failed to format transcript:', response.error);
      return null;
    }

    // Validate segments before processing
    const segments = response.data.segments || [];
    const validSegments = segments.filter(seg =>
      seg &&
      seg.text &&
      typeof seg.text === 'string' &&
      seg.text.trim().length > 0
    );

    if (validSegments.length === 0) {
      console.error('❌ [AI] No valid segments in response');
      return null;
    }

    // Calculate proper timing if needed
    const totalDuration = transcript[transcript.length - 1].endTime - transcript[0].startTime;
    const fullText = transcript.map(line => line.text || '').join('');
    const avgTimePerChar = fullText.length > 0 ? totalDuration / fullText.length : 3;
    let currentTime = transcript[0].startTime || 0;

    // Convert to the expected format with proper timing
    const formattedTranscript = validSegments.map((seg, index) => {
      const duration = seg.text.length * avgTimePerChar;
      const result = {
        id: seg.id || `seg_${index + 1}`,
        text: seg.text,
        startTime: seg.startTime !== undefined ? seg.startTime : currentTime,
        endTime: seg.endTime !== undefined ? seg.endTime : currentTime + duration,
        words: [seg.text],
        translation: seg.translation
      };

      // Update currentTime for next segment if we're calculating
      if (seg.startTime === undefined) {
        currentTime += duration;
      }

      return result;
    });

    // Log statistics
    const lengths = formattedTranscript.map(s => s.text.length);
    const avgLength = lengths.reduce((a, b) => a + b, 0) / lengths.length;
    const longSegments = lengths.filter(l => l > 20).length;

    console.log(`✅ [AI] Successfully formatted ${formattedTranscript.length} segments`);
    console.log(`📊 [AI] Avg length: ${avgLength.toFixed(1)} chars, Long segments (>20): ${longSegments}/${formattedTranscript.length}`);

    if (response.cached) {
      console.log(`💾 [AI] Response was cached`);
    }

    if (response.usage) {
      console.log(`💰 [AI] Cost: $${response.usage.estimatedCost.toFixed(4)} | Tokens: ${response.usage.totalTokens}`);
    }

    if (longSegments > 0) {
      console.warn(`⚠️ [AI] ${longSegments} segments exceed 20 chars - may be difficult for shadowing`);
    }

    return formattedTranscript;

  } catch (error: any) {
    console.error('❌ [AI] Error formatting transcript:', error);
    console.error('❌ [AI] Error details:', {
      name: error?.name || 'Unknown',
      message: error?.message || String(error),
      code: error?.code,
      details: error?.details
    });
    return null;
  }
}

// Helper function to extract with YouTube-Transcript.io
async function extractWithYouTubeTranscriptIO(
  videoId: string | null,
  apiKey: string | undefined,
  contentId: string,
  isAuthenticated: boolean,
  videoMetadata: any,
  url: string
): Promise<NextResponse> {
  try {

    if (!videoId) {
      return NextResponse.json({
        success: false,
        error: 'INVALID_VIDEO_ID',
        message: 'Could not extract video ID from URL'
      });
    }

    // YouTube-Transcript.io API endpoint
    const apiUrl = `https://youtube-transcript.io/api/transcript`;

    // Prepare request parameters
    const params: any = {
      video_id: videoId,
      lang: 'ja' // Request Japanese transcripts
    };

    // Add API key if provided (for paid plans)
    const headers: any = {
      'Accept': 'application/json',
      'User-Agent': 'Moshimoshi/1.0'
    };

    if (apiKey) {
      headers['Authorization'] = `Bearer ${apiKey}`;
    }

    const response = await axios.get(apiUrl, {
      params,
      headers,
      timeout: 15000
    });

    if (response.data && response.data.transcript) {
      const transcript = response.data.transcript.map((segment: any, index: number) => ({
        id: String(index + 1),
        text: segment.text || '',
        startTime: segment.start || index * 5,
        endTime: segment.end || segment.start + segment.duration || (index + 1) * 5,
        words: (segment.text || '').split(/[\s、。！？]/g).filter((w: string) => w.length > 0)
      }));

      // Save to cache only for authenticated users
      if (isAuthenticated) {
        try {
          await transcriptCache.set({
            contentId,
            contentType: 'youtube',
            videoUrl: url,
            videoTitle: videoMetadata?.title || response.data.title || 'Unknown',
            transcript,
            language: response.data.language || 'ja',
            metadata: {
              youtubeVideoId: videoId,
              channelName: videoMetadata?.channelTitle,
              uploadDate: videoMetadata?.publishedAt,
              thumbnailUrl: videoMetadata?.thumbnails?.medium?.url,
              duration: videoMetadata?.duration,
              method: 'youtube-transcript-io'
            }
          });

        } catch (cacheError) {
          console.error('Failed to cache transcript:', cacheError);
        }
      }

      // Format transcript with AI if it's Japanese
      let formattedTranscript = null;
      if ((response.data.language || 'ja').startsWith('ja')) {
        formattedTranscript = await formatTranscriptWithAI(
          transcript,
          videoMetadata?.title || response.data.title,
          contentId
        );
      }

      await logApiUsage('youtube-transcript-io', true, undefined, { videoId });

      // Only cache if we have the AI-processed version
      if (formattedTranscript && formattedTranscript.length > 0) {
        await transcriptCache.set({
          contentId,
          contentType: 'youtube',
          transcript: formattedTranscript, // Use AI-processed version as main transcript
          formattedTranscript: formattedTranscript,
          language: response.data.language || 'ja',
          videoUrl: url,
          videoTitle: videoMetadata?.title || response.data.title || 'Unknown',
          metadata: {
            youtubeVideoId: videoId,
            channelName: videoMetadata?.channelTitle,
            uploadDate: videoMetadata?.publishedAt,
            thumbnailUrl: videoMetadata?.thumbnails?.high?.url,
            thumbnails: videoMetadata?.thumbnails,
            description: videoMetadata?.description,
            wasFormatted: true,
            formattingModel: 'gpt-3.5-turbo'
          }
        });
        console.log('✅ Cached AI-processed transcript for:', videoId);
      } else {
        console.log('⏭️ Skipping cache - no AI-processed transcript available');
      }

      return NextResponse.json({
        success: true,
        transcript,
        formattedTranscript,
        language: response.data.language || 'ja',
        videoTitle: videoMetadata?.title || response.data.title || 'Unknown',
        videoMetadata: videoMetadata,
        method: 'youtube-transcript-io',
        hasFormattedVersion: !!formattedTranscript
      });
    } else {
      throw new Error('No transcript data in response');
    }
  } catch (error: any) {
    console.error('YouTube-Transcript.io error:', error.message);

    await logApiUsage('youtube-transcript-io', false, error.message, { videoId });

    // Handle specific error cases
    if (error.response?.status === 429) {
      return NextResponse.json({
        success: false,
        error: 'RATE_LIMIT',
        message: 'YouTube-Transcript.io rate limit exceeded. Please try again later or use a different provider.'
      });
    } else if (error.response?.status === 401) {
      return NextResponse.json({
        success: false,
        error: 'AUTH_FAILED',
        message: 'Invalid API key for YouTube-Transcript.io. Please check your API key.'
      });
    } else if (error.response?.status === 404) {
      return NextResponse.json({
        success: false,
        error: 'NO_TRANSCRIPT',
        message: 'No transcript available for this video on YouTube-Transcript.io'
      });
    }

    return NextResponse.json({
      success: false,
      error: 'EXTRACTION_FAILED',
      message: error.message || 'Failed to extract transcript via YouTube-Transcript.io'
    });
  }
}

