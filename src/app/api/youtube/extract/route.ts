// Helper function to get available caption tracks using YouTube Data API
async function getAvailableCaptionTracks(videoId: string): Promise<{
  tracks: CaptionTrack[];
  hasJapanese: boolean;
} | null> {
  try {
    const apiKey = process.env.GOOGLE_API_KEY || process.env.YOUTUBE_API_KEY;
    if (!apiKey) {
      console.warn('YouTube API key not configured, skipping caption detection');
      return null;
    }

    const response = await axios.get(`${YOUTUBE_API_BASE}/captions`, {
      params: {
        part: 'snippet',
        videoId: videoId,
        key: apiKey
      },
      timeout: 5000
    });

    const tracks = response.data.items.map((track: any) => ({
      language: track.snippet.language,
      name: track.snippet.name,
      isManual: track.snippet.trackKind !== 'ASR',
      isAutoGenerated: track.snippet.trackKind === 'ASR',
      trackId: track.id
    }));

    return {
      tracks,
      hasJapanese: tracks.some(track =>
        track.language === 'ja' || track.language.startsWith('ja-')
      )
    };

  } catch (error: any) {
    console.warn('Caption detection failed, continuing with extraction:', error.message);
    return null;
  }
}

